#!/usr/bin/env node

/**
 * Generate TypeScript types from .env.example
 * 
 * This script reads the .env.example file and generates
 * TypeScript type definitions for all environment variables.
 */

const fs = require('fs');
const path = require('path');

const ENV_EXAMPLE_PATH = path.join(__dirname, '../.env.example');
const OUTPUT_PATH = path.join(__dirname, '../src/types/env.d.ts');

const generateEnvTypes = () => {
  console.log('🔧 Generating environment variable types...');
  
  try {
    // Read .env.example
    const content = fs.readFileSync(ENV_EXAMPLE_PATH, 'utf8');
    
    // Extract variable names
    const varRegex = /^([A-Za-z0-9_]+)=/gm;
    const matches = [...content.matchAll(varRegex)];
    const varNames = matches.map(m => m[1]);
    
    // Generate TypeScript declarations
    let typeContent = `/**
 * Environment variable type definitions
 * Auto-generated from .env.example
 * Do not edit this file directly
 */

declare namespace NodeJS {
  interface ProcessEnv {
    NODE_ENV: 'development' | 'production' | 'test';
`;

    varNames.forEach(varName => {
      const isOptional = varName.includes('OPTIONAL') || 
                         varName.includes('_KEY') ||
                         varName.includes('_ID') ||
                         varName.includes('_TOKEN');
      
      const comment = isOptional ? '// Optional' : '// Required';
      typeContent += `    ${varName}: string; ${comment}\n`;
    });
    
    typeContent += `  }
}

// Import.meta.env types for Vite
interface ImportMetaEnv {
`;

    varNames.forEach(varName => {
      typeContent += `  readonly ${varName}: string;\n`;
    });
    
    typeContent += `}

interface ImportMeta {
  readonly env: ImportMetaEnv;
}
`;
    
    // Write file
    fs.writeFileSync(OUTPUT_PATH, typeContent);
    console.log(`✅ Generated types at ${OUTPUT_PATH}`);
    
  } catch (error) {
    console.error('❌ Failed to generate types:', error.message);
    process.exit(1);
  }
};

generateEnvTypes();